"""Regenerate the question list in docs/open-questions.md from the docs.

    python3 site/open_questions.py           # rewrite the generated part
    python3 site/open_questions.py --check   # exit 1 if it is stale

Every doc's "## Open questions" (and the sketches' "## Questions it raises")
is read bullet by bullet. A bullet that starts "**Topic:** answered ..." is a
pointer to an answer elsewhere; one that ends "(deliberately open)" is left as
story space; the rest are open. The generated part of open-questions.md sits
between the two marker comments and is never edited by hand: edit the docs'
own Open questions, then run this script.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
LEDGER = DOCS / "open-questions.md"
BEGIN = "<!-- generated by site/open_questions.py: do not edit below -->"
END = "<!-- end of generated part -->"
SECTION = re.compile(r"^## (Open questions|Questions it raises)\s*$")
TAG = "(deliberately open)"

# Each doc's questions are listed under one theme.
THEMES = [
    ("The hole and the Lantern", ["full-swarm", "sgr-a-scope", "matter-delivery", "hole-choice"]),
    ("Habitats and materials", ["habitat-design", "raft-habitat", "element-cycles"]),
    ("Getting around", ["drum-transport", "raft-transport"]),
    ("Energy and food", ["energy-budget", "xray-power", "food-system", "cuisine"]),
    ("Economy and governance", ["economy", "governance", "daily-life"]),
    ("People and culture", ["people", "families", "open-drums", "ashgrove", "wander-year", "third-chair", "sorrel", "eating-out"]),
    ("Earlier eras: the ring design study", ["swarm-rings", "ring-weave"]),
]


def slugify(s):
    """Heading ids as the site makes them (site/build.py)."""
    s = s.lower().replace("*", "")
    s = re.sub(r"[^\w\s-]", "", s)
    return re.sub(r"[\s_]+", "-", s).strip("-") or "section"


def questions(path):
    """(section heading, [bullet text]) for one doc, or (None, [])."""
    lines = path.read_text(encoding="utf-8").split("\n")
    heading, items, cur = None, [], None
    for line in lines:
        m = SECTION.match(line)
        if m:
            heading, cur = m.group(1), None
            continue
        if heading and (line.startswith("## ") or line.startswith("# ")):
            break
        if not heading:
            continue
        if re.match(r"^\s*[-*] ", line):
            cur = re.sub(r"^\s*[-*] ", "", line).strip()
            items.append(cur)
        elif line.strip() and items:
            items[-1] += " " + line.strip()
    return heading, items


def status(text):
    if re.match(r"^\*\*[^*]+:\*\* answered\b", text):
        return "answered"
    if text.rstrip().endswith(TAG):
        return "story"
    return "open"


def collect():
    docs = {p.stem: p for p in sorted(DOCS.glob("*.md")) if p.stem != "open-questions"}
    themed = {s for _, slugs in THEMES for s in slugs}
    rows = []
    for theme, slugs in THEMES + [("Other docs", sorted(set(docs) - themed))]:
        for slug in slugs:
            if slug not in docs:
                continue
            heading, items = questions(docs[slug])
            for text in items:
                if text.startswith("None at present"):
                    continue
                rows.append(dict(theme=theme, doc=slug, heading=heading, text=text, status=status(text)))
    return rows


def render(rows):
    count = {k: sum(r["status"] == k for r in rows) for k in ("open", "story", "answered")}
    docs_with = len({r["doc"] for r in rows if r["status"] != "answered"})
    out = [
        "## Status",
        "",
        "| | Questions |",
        "|---|---|",
        f"| Open | {count['open']} |",
        f"| Deliberately open (story space) | {count['story']} |",
        f"| Answered elsewhere, with a pointer left in the doc | {count['answered']} |",
        f"| Docs with questions still open | {docs_with} |",
        "",
        "## The questions by theme",
        "Each links to its doc's own list, which is the source. Answered questions are left out here; their pointers stay in the docs.",
        "",
    ]
    themes = []
    for r in rows:
        if r["theme"] not in themes:
            themes.append(r["theme"])
    for theme in themes:
        live = [r for r in rows if r["theme"] == theme and r["status"] != "answered"]
        if not live:
            continue
        out.append(f"### {theme}")
        for r in live:
            text = r["text"]
            if r["status"] == "story":
                text = text[: -len(TAG)].rstrip() + " *(deliberately open)*"
            link = f"[{r['doc']}.md]({r['doc']}.md#{slugify(r['heading'])})"
            out.append(f"- {link}: {text}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def regenerate(text, rows):
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{LEDGER} is missing its generated-part markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n\n{render(rows)}\n{END}{tail}"


def main(argv):
    check = "--check" in argv
    text = LEDGER.read_text(encoding="utf-8")
    new = regenerate(text, collect())
    if new == text:
        print("open-questions.md is up to date")
        return 0
    if check:
        print(f"ERROR: {LEDGER.relative_to(ROOT)} is stale: a doc's Open questions changed.\n"
              f"Run: python3 site/open_questions.py", file=sys.stderr)
        return 1
    LEDGER.write_text(new, encoding="utf-8")
    print(f"rewrote {LEDGER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
